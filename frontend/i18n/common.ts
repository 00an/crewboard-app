export type CommonLocale = keyof typeof commonTranslations;
export type CommonText = (typeof commonTranslations)[CommonLocale];

export function useCommonText(locale: string | undefined): CommonText {
  return commonTranslations[(locale as CommonLocale) ?? "en"] ?? commonTranslations.en;
}
